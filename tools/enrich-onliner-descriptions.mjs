function buildFullDescription(product, categorySlug) {
  const name = product.name || 'Товар';
  const brand = product.brand || '';
  const color = product.color && product.color !== '—' ? product.color : null;
  const meta = CATEGORY_META[categorySlug] || CATEGORY_META.home;
  const imgFile = imageBasename(product);
  const specLine = specLineFromJson(product, categorySlug);
  const visual = VISUAL_OVERRIDES[imgFile];

  if (isAssetVitrina(product)) {
    const lead = `${name} — служебная карточка витрины каталога (привязка к иллюстрации или файлу в репозитории).`;
    const parts = [
      lead,
      '',
      `В двух словах: ${meta.line}`,
      '',
      '## Описание',
      '',
      `✅ Карточка используется для проверки вёрстки, путей к изображениям и загрузки тестовых данных в базу.`,
      `✅ Фото или SVG хранится в каталоге public/assets/products/; путь в API: ${product.image || '—'}.`,
      '✅ Торговые характеристики и цена для таких позиций могут быть условными — уточняйте реальный ассортимент у продавца.',
      '',
      '## Покупка и уточнения',
      '',
      'Оформление заказа, доставка и гарантия — по правилам магазина Белтелеком. Для боевых SKU замените карточку на товар с полной спецификацией.',
    ];
    return parts.join('\n');
  }

  const brandPhrase =
    brand && brand !== 'demo' && brand !== 'asset'
      ? `от ${brand.charAt(0).toUpperCase() + brand.slice(1)}`
      : 'представленный в каталоге';

  let lead = `${name} — ${meta.noun} ${brandPhrase}`;
  if (color) lead += `, заявленный цвет: ${color}`;

  const bullets = bulletsForCategory(categorySlug, product);
  if (visual) bullets.unshift(visual);

  const checklist = bullets.map((t) => `✅ ${t}`).join('\n');

  const priceNote =
    product.price != null && Number(product.price) > 0
      ? `Ориентировочная цена на витрине: ${Number(product.price).toLocaleString('ru-RU')} BYN (может отличаться в салоне).`
      : 'Цену и акции уточняйте у продавца.';

  const parts = [
    lead + '.',
    '',
    `В двух словах: ${specLine}`,
    '',
    '## Описание',
    '',
    checklist,
    '',
    '## Характеристики и комплектация',
    '',
    `✅ Подробная таблица параметров приведена ниже на странице товара (блок «Характеристики»). Если какого-то поля нет, его можно запросить у менеджера или взять из официального сайта ${brand && brand !== 'demo' ? brand : 'производителя'}.`,
    `✅ ${priceNote}`,
    '✅ Фотография соответствует выбранной карточке каталога; внешний вид упаковки и комплекта в рознице могут обновляться производителем.',
    '',
    '## Покупка в Минске и по Беларуси',
    '',
    'Уточняйте наличие в салонах связи, возможность резерва, доставку и расширенную гарантию. При необходимости сравните модель с аналогами в каталоге Onliner или на сайте производителя — мы ориентируемся на такой же уровень детализации описания для удобства покупателя.',
  ];

  return parts.join('\n');
}

function shortDescription(fullText, product) {
  const firstBlock = fullText.split(/\n\n+/)[0] || '';
  const extra = product.specs && product.specs['Экран'] ? ` ${product.specs['Экран']}.` : '';
  const s = (firstBlock + extra).replace(/\s+/g, ' ').trim();
  if (s.length <= 200) return s;
  return s.slice(0, 197).trim() + '…';
}

function main() {
  const jsonFiles = fs
    .readdirSync(PRODUCTS_DIR)
    .filter((f) => f.endsWith('.json') && /^[a-z0-9_-]+\.json$/.test(f));

  let n = 0;
  for (const file of jsonFiles) {
    const categorySlug = file.replace(/\.json$/, '');
    const p = path.join(PRODUCTS_DIR, file);
    const data = JSON.parse(fs.readFileSync(p, 'utf8'));
    const items = data.products;
    if (!Array.isArray(items)) continue;
    for (const product of items) {
      const full = buildFullDescription(product, categorySlug);
      product.full_description = full;
      product.description = shortDescription(full, product);
      n++;
    }
    fs.writeFileSync(p, JSON.stringify(data, null, 2) + '\n', 'utf8');
  }
  console.log(`Обновлено описаний: ${n} товаров в ${jsonFiles.length} категориях.`);
}

main();
