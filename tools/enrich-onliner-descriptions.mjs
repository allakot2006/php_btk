function imageBasename(product) {
  const img = product.image || '';
  return img.split('/').pop() || '';
}

/** Короткий служебный текст только для SVG-иллюстраций витрины; JPG/PNG — полное описание как у товара. */
function isAssetVitrina(product) {
  const i = product.image || '';
  return /seed-illu-[^/]+\.svg$/i.test(i);
}

function specLineFromJson(product, categorySlug) {
  const specs = product.specs && typeof product.specs === 'object' ? product.specs : {};
  const skip = new Set(['Фото', 'Файл', 'Папка', 'sections']);
  const parts = [];
  for (const [k, v] of Object.entries(specs)) {
    if (skip.has(k)) continue;
    if (v == null || String(v).trim() === '' || String(v) === '—') continue;
    parts.push(`${k}: ${v}`);
  }
  if (parts.length) return parts.join('; ') + '.';
  const m = CATEGORY_META[categorySlug];
  return m ? m.line : 'Параметры уточняйте по выбранной комплектации.';
}

